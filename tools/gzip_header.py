"""gzip_header.py - PC tool: gzip a file and write it as a C header for the chip.

    python tools/gzip_header.py webpage.html webpage_gz.h

The chip serves these bytes as they are, with "Content-Encoding: gzip"; the
browser unpacks them. Same input -> same output (no time stamp, mtime=0), so
an unchanged page gives a byte-identical header. Run by the Makefile.
"""
import gzip
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gzip_header.py IN OUT.h")
    src, out = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    packed = gzip.compress(data, compresslevel=9, mtime=0)
    lines = [
        "/* Generated by tools/gzip_header.py from %s (from webpage.h). Do not edit:" % src,
        " * edit webpage.h; the Makefile regenerates this file. */",
        "#ifndef WEBPAGE_GZ_H",
        "#define WEBPAGE_GZ_H",
        "",
        "#include <avr/pgmspace.h>",
        "",
        "#define WEB_PAGE_PLAIN_LEN %d" % len(data),
        "#define WEB_PAGE_GZ_LEN %d" % len(packed),
        "",
        "static const uint8_t WEB_PAGE_GZ[WEB_PAGE_GZ_LEN] PROGMEM = {",
    ]
    for i in range(0, len(packed), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in packed[i:i + 16]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("%s: %d bytes -> %d gzipped (%s)" % (src, len(data), len(packed), out))


if __name__ == "__main__":
    main()
