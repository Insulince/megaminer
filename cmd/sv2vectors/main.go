// sv2vectors prints sv2crypto_vectors.h: expected results for sv2crypto.c,
// computed with Go's standard library and golang.org/x/crypto. It plays the
// same part gen_vectors.py plays for blake2b.c.
//
//	go run ./cmd/sv2vectors > tests/sv2/sv2crypto_vectors.h
package main

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/binary"
	"fmt"
	"io"

	"golang.org/x/crypto/chacha20poly1305"
	"golang.org/x/crypto/hkdf"
)

// pattern returns n bytes that differ per seed, without any randomness, so the
// header is identical every time it is generated.
func pattern(n int, seed byte) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(i*7+3) ^ seed
	}
	return b
}

func cArray(b []byte) string {
	if len(b) == 0 {
		return "{0}"
	}
	s := "{"
	for i, v := range b {
		if i > 0 {
			s += ","
		}
		s += fmt.Sprintf("0x%02x", v)
	}
	return s + "}"
}

func main() {
	fmt.Println("/* Generated by: go run ./cmd/sv2vectors > sv2crypto_vectors.h  -- do not edit. */")
	fmt.Println("/* The chip build defines SV2_VECTOR_ATTR as PROGMEM to keep these in flash, not RAM. */")
	fmt.Println("#ifndef SV2_VECTOR_ATTR")
	fmt.Println("#define SV2_VECTOR_ATTR")
	fmt.Println("#endif")
	fmt.Println()

	// SHA-256 at lengths around the 55/56 and 64-byte padding boundaries.
	shaLens := []int{0, 1, 3, 55, 56, 57, 63, 64, 65, 119, 120, 200}
	fmt.Println("struct sha_vector { uint16_t len; uint8_t data[200]; uint8_t want[32]; };")
	fmt.Println("static const struct sha_vector sha_vectors[] SV2_VECTOR_ATTR = {")
	for _, n := range shaLens {
		d := pattern(n, 0x11)
		sum := sha256.Sum256(d)
		fmt.Printf("  {%d, %s, %s},\n", n, cArray(d), cArray(sum[:]))
	}
	fmt.Println("};")
	fmt.Println()

	// HMAC-SHA256.
	fmt.Println("struct hmac_vector { uint8_t key_len; uint8_t key[64]; uint16_t len; uint8_t data[100]; uint8_t want[32]; };")
	fmt.Println("static const struct hmac_vector hmac_vectors[] SV2_VECTOR_ATTR = {")
	for _, c := range [][2]int{{32, 0}, {32, 33}, {1, 100}, {64, 64}} {
		k, d := pattern(c[0], 0x22), pattern(c[1], 0x33)
		m := hmac.New(sha256.New, k)
		m.Write(d)
		fmt.Printf("  {%d, %s, %d, %s, %s},\n", c[0], cArray(k), c[1], cArray(d), cArray(m.Sum(nil)))
	}
	fmt.Println("};")
	fmt.Println()

	// Noise HKDF, two outputs: with 32 bytes of material, and with none (Split).
	fmt.Println("struct hkdf_vector { uint8_t ck[32]; uint8_t len; uint8_t material[32]; uint8_t want1[32]; uint8_t want2[32]; };")
	fmt.Println("static const struct hkdf_vector hkdf_vectors[] SV2_VECTOR_ATTR = {")
	for _, n := range []int{32, 0} {
		ck, ikm := pattern(32, 0x44), pattern(n, 0x55)
		out := make([]byte, 64)
		if _, err := io.ReadFull(hkdf.New(sha256.New, ikm, ck, nil), out); err != nil {
			panic(err)
		}
		fmt.Printf("  {%s, %d, %s, %s, %s},\n", cArray(ck), n, cArray(ikm), cArray(out[:32]), cArray(out[32:]))
	}
	fmt.Println("};")
	fmt.Println()

	// ChaCha20-Poly1305 with Noise's nonce (4 zero bytes, then the counter LE).
	// Sizes cover the ones SV2 uses (6-byte header, 64-byte key, 74-byte
	// certificate) and the 16- and 64-byte block boundaries.
	type aeadCase struct {
		counter uint64
		adLen   int
		len     int
	}
	cases := []aeadCase{
		{0, 0, 0}, {0, 32, 0}, {1, 0, 6}, {2, 32, 64}, {3, 32, 74},
		{4, 0, 15}, {5, 0, 16}, {6, 0, 17}, {7, 5, 63}, {8, 0, 65},
		{0x0102030405060708, 13, 130}, {9, 0, 200},
	}
	fmt.Println("struct aead_vector { uint8_t key[32]; uint64_t counter; uint8_t ad_len; uint8_t ad[32]; uint16_t len; uint8_t plain[200]; uint8_t sealed[216]; };")
	fmt.Println("static const struct aead_vector aead_vectors[] SV2_VECTOR_ATTR = {")
	for i, c := range cases {
		key := pattern(32, byte(0x60+i))
		ad := pattern(c.adLen, 0x77)
		pt := pattern(c.len, byte(0x80+i))
		a, err := chacha20poly1305.New(key)
		if err != nil {
			panic(err)
		}
		nonce := make([]byte, 12)
		binary.LittleEndian.PutUint64(nonce[4:], c.counter)
		sealed := a.Seal(nil, nonce, pt, ad)
		fmt.Printf("  {%s, 0x%016xULL, %d, %s, %d, %s, %s},\n",
			cArray(key), c.counter, c.adLen, cArray(ad), c.len, cArray(pt), cArray(sealed))
	}
	fmt.Println("};")
}
