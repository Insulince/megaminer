// sv2curvevectors prints sv2curve_vectors.h: expected results for sv2curve.c,
// computed with btcec (a widely used Go secp256k1 library).
//
//	go run ./cmd/sv2curvevectors > tests/sv2/sv2curve_vectors.h
package main

import (
	"crypto/sha256"
	"fmt"
	"strings"

	"github.com/btcsuite/btcd/btcec/v2"
	"github.com/btcsuite/btcd/btcec/v2/ellswift"
	"github.com/btcsuite/btcd/btcec/v2/schnorr"
)

// bytesFor returns n repeatable pseudo-random bytes for a label, so the header
// is identical every time it is generated.
func bytesFor(label string, n int) []byte {
	var out []byte
	for i := 0; len(out) < n; i++ {
		h := sha256.Sum256([]byte(fmt.Sprintf("%s/%d", label, i)))
		out = append(out, h[:]...)
	}
	return out[:n]
}

func cArray(b []byte) string {
	var sb strings.Builder
	sb.WriteString("{")
	for i, v := range b {
		if i > 0 {
			sb.WriteString(",")
		}
		fmt.Fprintf(&sb, "0x%02x", v)
	}
	sb.WriteString("}")
	return sb.String()
}

func decode(ell []byte) []byte {
	var u, t btcec.FieldVal
	if u.SetByteSlice(ell[0:32]) {
		u.Normalize()
	}
	if t.SetByteSlice(ell[32:64]) {
		t.Normalize()
	}
	x, err := ellswift.XSwiftEC(&u, &t)
	if err != nil {
		panic(err)
	}
	x.Normalize()
	return x.Bytes()[:]
}

func privFor(label string) *btcec.PrivateKey {
	priv, _ := btcec.PrivKeyFromBytes(bytesFor(label, 32))
	return priv
}

func main() {
	fmt.Println("/* Generated by: go run ./cmd/sv2curvevectors > sv2curve_vectors.h  -- do not edit. */")
	fmt.Println("/* The chip build defines SV2_VECTOR_ATTR as PROGMEM to keep these in flash, not RAM. */")
	fmt.Println("#ifndef SV2_VECTOR_ATTR")
	fmt.Println("#define SV2_VECTOR_ATTR")
	fmt.Println("#endif")
	fmt.Println()

	// ElligatorSwift decoding, including the awkward inputs: zero halves and
	// values at or above the field prime.
	var ells [][]byte
	for i := 0; i < 24; i++ {
		ells = append(ells, bytesFor(fmt.Sprintf("ell%d", i), 64))
	}
	zero, ones := make([]byte, 32), make([]byte, 32)
	for i := range ones {
		ones[i] = 0xff
	}
	r := bytesFor("special", 32)
	for _, pair := range [][2][]byte{{zero, r}, {r, zero}, {zero, zero}, {ones, r}, {r, ones}, {ones, ones}} {
		ells = append(ells, append(append([]byte{}, pair[0]...), pair[1]...))
	}
	fmt.Println("struct decode_vector { uint8_t ell[64]; uint8_t x[32]; };")
	fmt.Println("static const struct decode_vector decode_vectors[] SV2_VECTOR_ATTR = {")
	for _, e := range ells {
		fmt.Printf("  {%s, %s},\n", cArray(e), cArray(decode(e)))
	}
	fmt.Println("};")
	fmt.Println()

	// Secret key -> public key x coordinate (to check our own encodings).
	fmt.Println("struct key_vector { uint8_t priv[32]; uint8_t x[32]; };")
	fmt.Println("static const struct key_vector key_vectors[] SV2_VECTOR_ATTR = {")
	for i := 0; i < 8; i++ {
		priv := privFor(fmt.Sprintf("key%d", i))
		fmt.Printf("  {%s, %s},\n", cArray(priv.Serialize()), cArray(schnorr.SerializePubKey(priv.PubKey())))
	}
	fmt.Println("};")
	fmt.Println()

	// v2_ecdh in both roles.
	fmt.Println("struct ecdh_vector { uint8_t priv[32]; uint8_t theirs[64]; uint8_t ours[64]; uint8_t initiating; uint8_t secret[32]; };")
	fmt.Println("static const struct ecdh_vector ecdh_vectors[] SV2_VECTOR_ATTR = {")
	for i := 0; i < 8; i++ {
		priv := privFor(fmt.Sprintf("ecdh%d", i))
		var theirs, ours [64]byte
		copy(theirs[:], bytesFor(fmt.Sprintf("theirs%d", i), 64))
		copy(ours[:], bytesFor(fmt.Sprintf("ours%d", i), 64))
		initiating := i%2 == 0
		secret, err := ellswift.V2Ecdh(priv, theirs, ours, initiating)
		if err != nil {
			panic(err)
		}
		flag := 0
		if initiating {
			flag = 1
		}
		fmt.Printf("  {%s, %s, %s, %d, %s},\n", cArray(priv.Serialize()), cArray(theirs[:]), cArray(ours[:]), flag, cArray(secret[:]))
	}
	fmt.Println("};")
	fmt.Println()

	// Valid BIP340 signatures.
	fmt.Println("struct schnorr_vector { uint8_t pubkey[32]; uint8_t msg[32]; uint8_t sig[64]; };")
	fmt.Println("static const struct schnorr_vector schnorr_vectors[] SV2_VECTOR_ATTR = {")
	for i := 0; i < 8; i++ {
		priv := privFor(fmt.Sprintf("sign%d", i))
		msg := bytesFor(fmt.Sprintf("msg%d", i), 32)
		sig, err := schnorr.Sign(priv, msg)
		if err != nil {
			panic(err)
		}
		fmt.Printf("  {%s, %s, %s},\n", cArray(schnorr.SerializePubKey(priv.PubKey())), cArray(msg), cArray(sig.Serialize()))
	}
	fmt.Println("};")
}
