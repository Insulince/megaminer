"""Generate blake2b_vectors.h: expected digests from Python's hashlib.

hashlib's BLAKE2b is the reference implementation from the BLAKE2 authors,
so these are independent "real world" answers for test_blake2b.c to check
our own code against.

Run:  python tests/hash/gen_vectors.py   (writes it next to this script)
"""

import hashlib
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "blake2b_vectors.h")

# (input length, digest length). Input byte i is always (i % 251).
CASES = [
    (0, 64),      # empty message
    (3, 64),
    (127, 64),    # one byte short of a block
    (128, 64),    # exactly one block
    (129, 64),    # one byte into a second block
    (164, 64),    # the size of an XBT v2 block header
    (256, 64),    # exactly two blocks
    (1000, 64),
    (164, 32),    # shorter digest
]

lines = [
    "/* Generated by gen_vectors.py from Python's hashlib. Do not edit. */",
    "",
    "typedef struct {",
    "    unsigned inlen;",
    "    unsigned outlen;",
    "    const char *hex;",
    "} blake2b_vector;",
    "",
    "static const blake2b_vector VECTORS[] = {",
]
for inlen, outlen in CASES:
    data = bytes(i % 251 for i in range(inlen))
    digest = hashlib.blake2b(data, digest_size=outlen).hexdigest()
    lines.append(f'    {{ {inlen}, {outlen}, "{digest}" }},')
lines.append("};")
lines.append("")

with open(OUT, "w", newline="\n") as f:
    f.write("\n".join(lines))

print(f"wrote blake2b_vectors.h with {len(CASES)} vectors")
